-- Loads a profile of the box into Oracle Free through external tables (schema ALAMEDA).
-- Times printed here are private (licence rule of the course): they stay in salidas/.
WHENEVER SQLERROR CONTINUE
CONNECT system/lab@//localhost/FREEPDB1
CREATE OR REPLACE DIRECTORY caja_PERFIL AS '/caja/PERFIL';
GRANT READ ON DIRECTORY caja_PERFIL TO alameda;
CONNECT alameda/lab@//localhost/FREEPDB1
SET TIMING ON
SET LINESIZE 200
BEGIN FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('Pacientes','Protocolos','ResultadoItem','X_PAC','X_PRO','X_RES')) LOOP
  EXECUTE IMMEDIATE 'DROP TABLE "'||t.table_name||'" PURGE'; END LOOP; END;
/
CREATE TABLE x_pac ("IdPaciente" NUMBER, "Nombre" VARCHAR2(120), "DNI" VARCHAR2(20), "FechaNac" VARCHAR2(10),
  "Sexo" CHAR(1), "Telefono" VARCHAR2(60), "ObraSocial" VARCHAR2(40), "NroAfiliado" VARCHAR2(20))
  ORGANIZATION EXTERNAL (TYPE ORACLE_LOADER DEFAULT DIRECTORY caja_PERFIL ACCESS PARAMETERS (
    RECORDS DELIMITED BY '\r\n' CHARACTERSET WE8ISO8859P1 SKIP 1 NOBADFILE NOLOGFILE NODISCARDFILE
    FIELDS CSV WITH EMBEDDED TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"' MISSING FIELD VALUES ARE NULL)
  LOCATION ('Pacientes.csv')) REJECT LIMIT UNLIMITED;
CREATE TABLE x_pro ("IdProtocolo" NUMBER, "NroProtocolo" VARCHAR2(20), "IdPaciente" NUMBER, "Fecha" VARCHAR2(10),
  "Sede" CHAR(1), "ObraSocialTexto" VARCHAR2(40))
  ORGANIZATION EXTERNAL (TYPE ORACLE_LOADER DEFAULT DIRECTORY caja_PERFIL ACCESS PARAMETERS (
    RECORDS DELIMITED BY '\r\n' CHARACTERSET AL32UTF8 SKIP 1 NOBADFILE NOLOGFILE NODISCARDFILE
    FIELDS CSV WITH EMBEDDED TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"' MISSING FIELD VALUES ARE NULL)
  LOCATION ('Protocolos.csv')) REJECT LIMIT UNLIMITED;
CREATE TABLE x_res ("IdItem" NUMBER, "IdProtocolo" NUMBER, "CodAnalito" VARCHAR2(10), "Valor" VARCHAR2(40), "Unidad" VARCHAR2(10))
  ORGANIZATION EXTERNAL (TYPE ORACLE_LOADER DEFAULT DIRECTORY caja_PERFIL ACCESS PARAMETERS (
    RECORDS DELIMITED BY '\r\n' CHARACTERSET AL32UTF8 SKIP 1 NOBADFILE NOLOGFILE NODISCARDFILE
    FIELDS CSV WITH EMBEDDED TERMINATED BY ',' OPTIONALLY ENCLOSED BY '"' MISSING FIELD VALUES ARE NULL)
  LOCATION ('ResultadoItem.csv')) REJECT LIMIT UNLIMITED;
CREATE TABLE "Pacientes" AS SELECT "IdPaciente","Nombre","DNI",TO_DATE("FechaNac",'YYYY-MM-DD') "FechaNac","Sexo","Telefono","ObraSocial","NroAfiliado" FROM x_pac;
CREATE TABLE "Protocolos" AS SELECT "IdProtocolo","NroProtocolo","IdPaciente",TO_DATE("Fecha",'YYYY-MM-DD') "Fecha","Sede","ObraSocialTexto" FROM x_pro;
CREATE TABLE "ResultadoItem" AS SELECT * FROM x_res;
SELECT segment_name, ROUND(bytes/1048576) mb FROM user_segments WHERE segment_type='TABLE' ORDER BY 1;
SELECT COUNT(*) FROM "Pacientes";
SELECT COUNT(*) FROM "ResultadoItem";
SELECT "Nombre" FROM "Pacientes" WHERE "Nombre" LIKE 'NU%EZ%' FETCH FIRST 2 ROWS ONLY;
EXIT
