DROP TABLE IF EXISTS staging.lab_order_new;
CREATE TABLE staging.lab_order_new (
    lab_order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id   integer NOT NULL,
    ordered_on   date NOT NULL
);
